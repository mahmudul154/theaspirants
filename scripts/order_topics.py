"""Arrange selectable topics in a stable, curriculum-friendly order.

The database topic strings are intentionally left unchanged. This script only
changes their display order in src/topics.json, grouping foundations before
advanced/specialized topics and keeping exam/miscellaneous buckets last.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOPICS_PATH = ROOT / "src" / "topics.json"
COUNTS_PATH = ROOT / "src" / "question-counts.json"

TOPICS = json.loads(TOPICS_PATH.read_text(encoding="utf-8"))
COUNT_DATA = json.loads(COUNTS_PATH.read_text(encoding="utf-8"))
COUNTS = COUNT_DATA["subjects"]


def complete_order(subject: str, ordered: list[str]) -> list[str]:
    current = TOPICS[subject]
    if len(ordered) != len(set(ordered)):
        raise ValueError(f"Duplicate ordered topic in {subject}")
    missing = set(current) - set(ordered)
    extra = set(ordered) - set(current)
    if missing or extra:
        raise ValueError(f"{subject}: missing={sorted(missing)}, extra={sorted(extra)}")
    return ordered


def grouped_order(subject: str, groups: list[str], anchors: list[str] | None = None) -> list[str]:
    """Group by the first matching regex, then retain a stable useful order.

    Explicit anchors lead within each group. Remaining topics retain their
    existing popularity-oriented order, which puts broad topics before narrow
    variants without changing any topic labels.
    """
    current = TOPICS[subject]
    anchor_rank = {topic: index for index, topic in enumerate(anchors or [])}
    compiled = [re.compile(pattern, re.I) for pattern in groups]

    unmatched = [topic for topic in current if not any(pattern.search(topic) for pattern in compiled)]
    if unmatched:
        raise ValueError(f"Unclassified topics in {subject}: {unmatched}")

    def key(item: tuple[int, str]):
        old_index, topic = item
        group = next(i for i, pattern in enumerate(compiled) if pattern.search(topic))
        return group, anchor_rank.get(topic, 100_000 + old_index)

    ordered = [topic for _, topic in sorted(enumerate(current), key=key)]
    if set(ordered) != set(current) or len(ordered) != len(current):
        raise ValueError(f"Topic integrity failed for {subject}")
    return ordered


