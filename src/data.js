/* আগের কোডের মতো টপিক-মিশিয়ে + অপশন shuffle করে প্রশ্ন বাছাই */
export function mixQuestions(rows, limit) {
  const byTopic = {}
  rows.forEach(r => { const t = r.topic || 'Others'; (byTopic[t] ||= []).push(r) })
  Object.values(byTopic).forEach(a => a.sort(() => Math.random() - .5))
  const topics = Object.keys(byTopic).sort(() => Math.random() - .5)
  const out = []
  const n = limit ? Math.min(limit, rows.length) : rows.length
  while (out.length < n) {
    let added = false
    for (const t of topics) {
      if (out.length >= n) break
      if (byTopic[t].length) { out.push(byTopic[t].shift()); added = true }
    }
    if (!added) break
  }
  return out.map(r => ({ ...r, options: r.options ? [...r.options].sort(() => Math.random() - .5) : [] }))
}

