-- Required live-exam leaderboard table.
-- The current Supabase project returned 404 for public.exam_results, which is why
-- completed scheduled exams were not appearing on the leaderboard. Run this file
-- once in Supabase Dashboard → SQL Editor.

create table if not exists public.exam_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  user_name text not null default 'শিক্ষার্থী',
  user_avatar text,
  score numeric(5,2) not null check (score >= 0 and score <= 100),
  total_questions integer not null check (total_questions > 0),
  category text not null check (category like 'live:%' or category like 'live-archive:%'),
  created_at timestamptz not null default now()
);

create index if not exists exam_results_category_created_at_idx
  on public.exam_results (category, created_at desc);
create index if not exists exam_results_user_id_idx
  on public.exam_results (user_id, created_at desc);

alter table public.exam_results enable row level security;

grant select on public.exam_results to anon, authenticated;
grant insert on public.exam_results to authenticated;
grant usage, select on sequence public.exam_results_id_seq to authenticated;

drop policy if exists "Public can read live leaderboard results" on public.exam_results;
create policy "Public can read live leaderboard results"
  on public.exam_results
  for select
  to anon, authenticated
  using (category like 'live:%' or category like 'live-archive:%');

drop policy if exists "Users can submit their own live exam results" on public.exam_results;
create policy "Users can submit their own live exam results"
  on public.exam_results
  for insert
  to authenticated
  with check (
    auth.uid() = user_id
    and (category like 'live:%' or category like 'live-archive:%')
  );
